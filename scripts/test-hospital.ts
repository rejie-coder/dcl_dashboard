import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import Papa from 'papaparse';
import * as XLSX from 'xlsx';
import {normalizeHospitalRows,pointsFor,statistics,analyze,MONTHS} from '../src/lib/hospital/model';
import {parseImportFile} from '../src/lib/excel/parse-workbook';
const input=readFileSync('src/data/hambantota.csv','utf8');
const result=normalizeHospitalRows(Papa.parse<Record<string,unknown>>(input,{header:true,skipEmptyLines:true}).data);
assert.equal(result.errors.length,0); assert.equal(result.duplicates,192);assert.equal(result.rows.length,192);assert.equal(new Set(result.rows.map(r=>r.name)).size,64);
const admissions=result.rows.filter(r=>r.name==='Admission');
assert.equal(statistics(pointsFor(admissions,false).map(p=>p.value!)).sum,266189);
assert.equal(pointsFor(admissions,true).filter(p=>p.value!==null).length,35);
assert.equal(pointsFor(admissions,false).filter(p=>p.value!==null).length,36);
const p=(vals:(number|null)[])=>vals.map((value,month)=>({year:2024,month,value,flags:[]}));
assert.equal(statistics([1,2,3]).sd,1);assert.equal(statistics([1,2,3,4]).median,2.5);assert.equal(statistics([]).mean,null);
const a=analyze(p([1,2,3,4,5,6]),p([1,2,3,4,5,6]),'sd',2,6);assert.ok(a.points[5].flags.includes('6-point trend'));
const gap=analyze(p([1,2,3,null,5,6,7]),p([1,2,3,null,5,6,7]),'sd',2,6);assert.ok(gap.points.every(p=>!p.flags.includes('6-point trend')));
const shift=analyze(p(Array(8).fill(20)),p([9,10,11]),'sd',2,6);assert.ok(shift.points[7].flags.includes('8-point shift'));assert.ok(shift.points[0].flags.includes('Above upper limit'));
const imr=analyze(p([1,3,5]),p([1,3,5]),'imr',3,6);assert.ok(Math.abs(imr.sigma!-2/1.128)<1e-9);
const raw={Code:'Test',Year:2024,...Object.fromEntries(MONTHS.map(m=>[m,1]))};
assert.equal(normalizeHospitalRows([raw,{...raw,Jan:2}]).errors.length,1);
assert.equal(normalizeHospitalRows([{...raw,Jan:'abc'}]).errors.length,1);
assert.equal(normalizeHospitalRows([{...raw,Jan:''}]).rows[0].values[0],null);
assert.equal(normalizeHospitalRows([{...raw,Jan:0}]).rows[0].values[0],0);
const csvParsed=await parseImportFile(new File([input],'hospital.csv',{type:'text/csv'}));assert.equal(normalizeHospitalRows(csvParsed.sheets[0].rows).duplicates,192);
const wb=XLSX.utils.book_new(); XLSX.utils.book_append_sheet(wb,XLSX.utils.json_to_sheet([raw]),'Hospital');
const excel=await parseImportFile(new File([XLSX.write(wb,{type:'array',bookType:'xlsx'})],'hospital.xlsx'));assert.equal(normalizeHospitalRows(excel.sheets[0].rows).rows[0].values[0],1);
console.log('PASS: supplied CSV, 192 duplicate exclusions, 64 indicators, totals, zero/missing handling, SD, median, moving-range limits, trends, shifts, gap breaks, invalid/conflicting rows, CSV and XLSX parsing.');
